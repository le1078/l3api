// TestCreditNoteWindow creditNote 的时段文案：此前硬编码 23:00–8:00，现按结构化
// promotion 输出准确窗口。窗口串本身与时点无关，可确定性断言；「当前生效/生效」
// 后缀依赖真实时钟，故按 p.Active(now) 预期（本测试只锁文案形态与窗口正确性）。
func TestCreditNoteWindow(t *testing.T) {
	now := time.Now().In(scheduleTZ)
	// 日窗型折扣：窗口必须是上游真实口径 23:00–07:50（不是硬编码的 8:00）。
	night := upstream.ModelInfo{ID: "glm-5.2", Credits: "x0.79", Promotion: &upstream.ModelPromotion{
		Label: "夜间折扣", Start: "23:00", End: "7:50", Credit: "0.50x", Factor: 0.5,
	}}
	wantNight := " · 夜间折扣 0.50x（23:00–07:50，当前生效）"
	if !night.Promotion.Active(now) {
		wantNight = " · 夜间折扣 0.50x（23:00–07:50 生效）"
	}
	if got := creditNote(night); got != wantNight {
		t.Errorf("night discount = %q want %q", got, wantNight)
	}
	if !strings.Contains(creditNote(night), "23:00–07:50") {
		t.Errorf("creditNote must carry the accurate window; got %q", creditNote(night))
	}
	// 免费 + 无日窗（限时免费兜底）→ 「免费」，不编造窗口。
	free := upstream.ModelInfo{ID: "hy3", Credits: "x0.05", Promotion: &upstream.ModelPromotion{
		Label: "限时免费", Credit: "0x",
	}}
	if got, want := creditNote(free), " · 免费"; got != want {
		t.Errorf("free no-window = %q want %q", got, want)
	}
	// 倍率 x0.00 → 免费（既有口径不变）。
	if got, want := creditNote(upstream.ModelInfo{Credits: "x0.00"}), " · 免费"; got != want {
		t.Errorf("x0.00 = %q want %q", got, want)
	}
	// 无活动 → 原倍率（既有口径不变）。
	if got, want := creditNote(upstream.ModelInfo{Credits: "x0.29"}), " · 倍率 x0.29"; got != want {
		t.Errorf("plain = %q want %q", got, want)
	}
	// 徽章兜底（无结构化促销）：hy4-preview 夜间免费 → 23:00–08:00。
	hy4 := upstream.ModelInfo{ID: "hy4-preview", Credits: "x0.29", Badge: "夜间免费"}
	got := creditNote(hy4)
	if !strings.Contains(got, "23:00") {
		t.Errorf("badge fallback must render a window; got %q", got)
	}
	// 未知徽章 → 只标徽章（不编造时段）。
	if got, want := creditNote(upstream.ModelInfo{Badge: "订阅优先"}), " · 订阅优先"; got != want {
		t.Errorf("unknown badge = %q want %q", got, want)
	}
}

